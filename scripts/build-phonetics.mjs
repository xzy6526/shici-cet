import { readFile, writeFile } from 'node:fs/promises';
import { words } from '../src/words.js';

const UK_COMMIT = '1062be14adc96c358f2087ac5449d72130c7a6f4';
const US_COMMIT = '43c3570eb3553bdd19fccd2bd0091534889af023';
const ukSource = await readFile(new URL('../data/raw/britfone.main.3.0.1.csv', import.meta.url), 'utf8');
const usSource = await readFile(new URL('../data/raw/ipa-dict.en_US.txt', import.meta.url), 'utf8');

function add(map, key, ipa) {
  if (!key || !ipa) return;
  const list = map.get(key) || [];
  if (!list.includes(ipa)) list.push(ipa);
  map.set(key, list);
}

const uk = new Map();
for (const line of ukSource.split(/\r?\n/)) {
  const index = line.indexOf(',');
  if (index < 1) continue;
  const word = line.slice(0, index).trim().replace(/\(\d+\)$/, '').toLowerCase();
  const ipa = line.slice(index + 1).replace(/\s+/g, '').trim();
  add(uk, word, ipa && `/${ipa}/`);
}

const us = new Map();
for (const line of usSource.split(/\r?\n/)) {
  const index = line.indexOf('\t');
  if (index < 1) continue;
  const word = line.slice(0, index).trim().toLowerCase();
  const ipa = line.slice(index + 1).trim();
  for (const match of ipa.matchAll(/\/([^/]+)\//g)) add(us, word, `/${match[1]}/`);
}

const phoneticSources = {
  uk: { name: 'Britfone', url: `https://github.com/JoseLlarena/Britfone/tree/${UK_COMMIT}`, license: 'MIT', commit: UK_COMMIT, verified: true },
  us: { name: 'ipa-dict en_US', url: `https://github.com/open-dict-data/ipa-dict/tree/${US_COMMIT}`, license: 'MIT for en_US upstream', commit: US_COMMIT, verified: true },
};
const phonetics = {};
for (const item of words) {
  const key = item.word.toLowerCase();
  const ukValues = uk.get(key) || [];
  const usValues = us.get(key) || [];
  if (!ukValues.length && !usValues.length) continue;
  phonetics[key] = {
    ...(ukValues.length ? { uk: { ipa: ukValues[0], variants: ukValues.slice(1), notation: 'Britfone uses strict IPA with stress marks attached to stressed vowels.' } } : {}),
    ...(usValues.length ? { us: { ipa: usValues[0], variants: usValues.slice(1) } } : {}),
  };
}

const output = new URL('../src/phonetics.js', import.meta.url);
await writeFile(output, `// Generated by scripts/build-phonetics.mjs. Do not hand-edit.\nexport const phoneticSources = ${JSON.stringify(phoneticSources, null, 2)};\nexport const verifiedPhonetics = ${JSON.stringify(phonetics, null, 2)};\n`);
console.log(JSON.stringify({ total: words.length, uk: words.filter((word) => phonetics[word.word]?.uk).length, us: words.filter((word) => phonetics[word.word]?.us).length, both: words.filter((word) => phonetics[word.word]?.uk && phonetics[word.word]?.us).length }));
